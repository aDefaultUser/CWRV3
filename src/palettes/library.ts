const CACHE = new Map<string, Palette>();
/** Palettes loaded from files by the user (palette selector "load from file"), kept in browser storage. */
const userPalettes = loadPref<Record<string, string>>('userPalettes', {}, isRecord);
for (const [name, text] of Object.entries(userPalettes)) {
  try { parsePalette(text); SRC[name] = text; } catch (err) { console.error(`CWRV3: stored palette ${name} is invalid and was skipped`, err); }
}

export function paletteNames(): string[] { return Object.keys(SRC); }
export function hasPalette(name: string): boolean { return name in SRC; }
export function paletteSource(name: string): string | undefined { return SRC[name]; }
/** A known palette. Unknown names are an error: settings only accept known names (see SettingsStore). */
export function getPalette(name: string): Palette {
  let p = CACHE.get(name);
  if (!p) {
    const src = SRC[name];
    if (src === undefined) throw new Error(`unknown palette "${name}"`);
    p = parsePalette(src);
    CACHE.set(name, p);
  }
  return p;
}
/** Registers a user palette (palette selector "load from file") and stores it; returns the palette and whether it was saved. */
export function registerPalette(text: string): { palette: Palette; saved: boolean } {
  const p = parsePalette(text);
  SRC[p.name] = text;
  CACHE.delete(p.name);
  userPalettes[p.name] = text;
  const saved = savePref('userPalettes', userPalettes, `palette ${p.name}`);
  return { palette: getPalette(p.name), saved };
}
